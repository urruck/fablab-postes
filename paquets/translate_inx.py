def translate_exact(s, dico):
    """Traduction par correspondance exacte."""
    return dico.get(s, None)

def translate_words(s, word_map):
    """Traduction mot par mot (pour les chaînes non trouvées exactement)."""
    result = s
    for pattern, replacement in word_map.items():
        result = re.sub(pattern, replacement, result)
    return result

def translate_submenu_attr(m):
    val = m.group(1)
    translated = SUBMENUS.get(val, val)
    return f'name="{translated}"'

def translate_name_tag(m):
    val = m.group(1)
    translated = NAMES.get(val, val)
    return f'<name>{translated}</name>'

def translate_gui_text(m):
    val = m.group(1)
    # Essai correspondance exacte
    t = GUI_TEXT_EXACT.get(val)
    if t:
        return f'gui-text="{t}"'
    # Sinon traduction mot par mot
    t2 = translate_words(val, WORD_MAP)
    if t2 != val:
        return f'gui-text="{t2}"'
    return m.group(0)

def translate_page_text(m):
    val = m.group(1)
    t = GUI_TEXT_EXACT.get(val, SUBMENUS.get(val))
    if t:
        return f'gui-text="{t}"'
    t2 = translate_words(val, WORD_MAP)
    if t2 != val:
        return f'gui-text="{t2}"'
    return m.group(0)

def process_file(path):
    try:
        with open(path, 'r', encoding='utf-8') as f:
            content = f.read()
    except UnicodeDecodeError:
        try:
            with open(path, 'r', encoding='latin-1') as f:
                content = f.read()
        except Exception:
            return False

    original = content

    # Sous-menus (sauf FabLab Boc@l déjà fait)
    content = re.sub(
        r'submenu name="([^"]+)"',
        lambda m: f'submenu name="{SUBMENUS.get(m.group(1), m.group(1))}"',
        content
    )

    # Noms d'extensions
    content = re.sub(
        r'<name>([^<]+)</name>',
        lambda m: f'<name>{NAMES.get(m.group(1).strip(), m.group(1))}</name>',
        content
    )

    # gui-text (paramètres et onglets)
    content = re.sub(r'gui-text="([^"]*)"', translate_gui_text, content)

    # gui-description
    def translate_gui_desc(m):
        val = m.group(1)
        t = translate_words(val, WORD_MAP)
        return f'gui-description="{t}"'
    content = re.sub(r'gui-description="([^"]*)"', translate_gui_desc, content)

    if content != original:
        with open(path, 'w', encoding='utf-8') as f:
            f.write(content)
        return True
    return False

