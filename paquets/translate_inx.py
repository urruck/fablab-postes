if __name__ == '__main__':
    ext_dir = sys.argv[1] if len(sys.argv) > 1 else '.'
    total = modified = 0
    for root, dirs, files in os.walk(ext_dir):
        for fn in files:
            if fn.endswith('.inx'):
                total += 1
                if process_file(os.path.join(root, fn)):
                    modified += 1
    print(f"Fichiers traités : {total} | Modifiés : {modified}")
